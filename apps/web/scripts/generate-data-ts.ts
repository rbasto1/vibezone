import * as fs from "fs";

import { db, models as modelsTable, providers as providersTable } from "@/db";
import { listModels } from "@/lib/trpc/models-list";
import { and, eq, exists, isNull } from "drizzle-orm";

const dstFolder = "../generated";

/**
 * Helper function to format an array of items with each item on its own line
 * for better git diff readability
 */
function stringifyList(items: unknown[]): string {
  if (!items.length) return "[\n]";

  const formattedItems = items.map((item) => JSON.stringify(item)).join(",\n");

  return `[\n${formattedItems}\n]`;
}

function stringifyRecord(record: Record<string, unknown>): string {
  const entries = Object.entries(record);
  if (!entries.length) return "{\n}";

  const formattedEntries = entries
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
    .join(",\n");

  return "{\n" + formattedEntries + "\n}";
}

function getGeneratedOutput(filename: string) {
  const currentPath = import.meta.url;
  const fullFilename = new URL(`${dstFolder}/${filename}`, currentPath)
    .pathname;
  const fullPath = fullFilename.substring(0, fullFilename.lastIndexOf("/"));

  return { fullFilename, fullPath };
}

async function generateModels() {
  const { fullFilename, fullPath } = getGeneratedOutput("models.ts");

  const models = await listModels();
  models.models.forEach(cleanup);
  models.providers.forEach(cleanup);

  if (!fs.existsSync(fullPath)) {
    fs.mkdirSync(fullPath);
  }
  const prevSize = fs.existsSync(fullFilename)
    ? fs.statSync(fullFilename).size
    : 1;
  const fileContents = [
    "// This file is auto-generated by generate-models-ts.ts\n",
    'import type { GetModelsListReturn } from "@/lib/trpc/models";\n',
    "export const models = {",
    "groups:",
    stringifyList(models.groups),
    ", models:",
    stringifyList(models.models),
    ", providers:",
    stringifyList(models.providers),
    "} as unknown as GetModelsListReturn;\n",
  ].join("");
  fs.writeFileSync(fullFilename, fileContents);
  const size = fs.statSync(fullFilename).size;
  const increasePercent = ((size - prevSize) / prevSize) * 100;
  const sign = increasePercent >= 0 ? "+" : "";
  const sizeKb = (size / 1024).toFixed(0);

  console.info(
    `✅ Models JSON generated successfully: ${fullFilename} (${sizeKb} KB, ${sign}${increasePercent.toFixed(1)}%)`
  );
}

async function generateModelsForLimiting() {
  const { fullFilename, fullPath } = getGeneratedOutput(
    "../../llm-worker/src/generated/models.ts"
  );

  const models = await db.query.models.findMany({
    where: and(isNull(modelsTable.deletedAt), isNull(modelsTable.hiddenAt)),
    columns: {
      id: true,
      isIncluded: true,
      isPremium: true,
    },
    orderBy: [modelsTable.id],
  });

  // Convert array to record with model id as key
  const modelsRecord = models.reduce(
    (acc, model) => {
      acc[model.id] = {
        ...(model.isIncluded ? { isIncluded: true } : {}),
        ...(model.isPremium ? { isPremium: true } : {}),
      };
      return acc;
    },
    {} as Record<string, { isIncluded?: true; isPremium?: true }>
  );

  const fileContents = [
    "// This file is auto-generated by generate-data-ts.ts\n",
    "export const models: Record<string, { isIncluded?: true; isPremium?: true }> = ",
    stringifyRecord(modelsRecord),
    ";\n",
  ].join("");

  if (!fs.existsSync(fullPath)) {
    fs.mkdirSync(fullPath, { recursive: true });
  }

  fs.writeFileSync(fullFilename, fileContents);

  console.info(
    `✅ Simplified models list generated successfully: ${fullFilename}`
  );
}

async function generateProvidersForPrivacyPolicy() {
  const { fullFilename, fullPath } = getGeneratedOutput("providers-privacy.ts");

  const providers = await db.query.providers.findMany({
    where: and(
      isNull(providersTable.deletedAt),
      exists(
        db
          .select()
          .from(modelsTable)
          .where(
            and(
              eq(modelsTable.providerId, providersTable.id),
              isNull(modelsTable.deletedAt),
              isNull(modelsTable.hiddenAt)
            )
          )
      )
    ),
    columns: {
      id: true,
      name: true,
      privacyPolicyUrl: true,
    },
    orderBy: [providersTable.name],
  });

  if (!fs.existsSync(fullPath)) {
    fs.mkdirSync(fullPath);
  }

  const providersData = providers.map((provider) => ({
    id: provider.id,
    name: provider.name,
    privacyPolicyUrl: provider.privacyPolicyUrl || null,
  }));

  const fileContents = [
    "// This file is auto-generated by generate-models-ts.ts\n",
    "import type { Provider } from '@/db';\n",
    "export type ProviderPrivacyInfo = Pick<Provider, 'id' | 'name' | 'privacyPolicyUrl'>;\n",
    "export const providersPrivacy: ProviderPrivacyInfo[] = ",
    stringifyList(providersData),
    ";\n",
  ].join("");

  fs.writeFileSync(fullFilename, fileContents);
  console.info(`✅ Generated providers privacy data at: ${fullFilename}`);
}

async function main() {
  try {
    await generateModels();
    await generateModelsForLimiting();
    await generateProvidersForPrivacyPolicy();
  } catch (error) {
    console.error("Error generating files:", error);
    process.exit(1);
  }
}

main();

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function cleanup(obj: any) {
  Object.keys(obj).forEach((key) => {
    if (obj[key] === false || obj[key] === null) {
      delete obj[key];
    }
  });
  delete obj.createdAt;
  delete obj.updatedAt;
}
